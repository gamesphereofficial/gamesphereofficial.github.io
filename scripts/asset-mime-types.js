export function getAssetMimeType(path, bytes) {
  const extension = path.split(".").pop()?.toLowerCase();
  if (extension === "ts" && bytes) {
    for (let offset = 0; offset < Math.min(bytes.length, 188 * 3); offset += 188) {
      if (bytes[offset] !== 0x47) return "application/typescript";
    }
    return bytes.length >= 188 ? "video/mp2t" : "application/typescript";
  }
  return MIME_TYPES[extension] || "application/octet-stream";
}
